"""Generate REPORT.md: family-wide BSD cross-check table + completeness audit.

Reads results.json (from bsd_family.py --out) + data/families.json + count.txt.
Usage: python scripts/make_report.py --results tmp/results_full.json --out REPORT.md
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", default="REPORT.md")
    args = ap.parse_args()

    with open(args.results, encoding="utf-8") as f:
        res = json.load(f)
    with open(os.path.join(REPO, "data", "families.json"), encoding="utf-8") as f:
        fam = json.load(f)
    curves = fam["curves"]

    def is_pass(r):
        return (
            r["conductor_rederived"]
            and r["sha_is_square"]
            and r["fe_selfcheck"]
            and r["torsion_agrees"]
            and r["mismatches"] == "none"
        )

    # completeness audit: raw allbsd heads vs count.txt ("N NNF" = isogeny
    # classes per conductor). families.json keeps only rank-0 curves, so the
    # witness runs on the raw head file (all ranks) for conductors <= 100.
    nnf = {}
    with open(os.path.join(REPO, "data", "count.txt"), encoding="utf-8") as f:
        for ln in f:
            p = ln.split()
            if len(p) == 2 and p[0].isdigit():
                nnf[int(p[0])] = int(p[1])
    head_cls, head_curves, head_rank0 = {}, {}, {}
    with open(os.path.join(REPO, "data", "allbsd_head.txt"), encoding="utf-8") as f:
        for ln in f:
            p = ln.split()
            if len(p) < 6 or not p[0].isdigit():
                continue
            N = int(p[0])
            if N > 100:
                continue  # heads are lexicographically sorted; small N reappears later
            head_cls.setdefault(N, set()).add(p[0] + " " + p[1])
            head_curves[N] = head_curves.get(N, 0) + 1
            if int(p[4]) == 0:
                head_rank0[N] = head_rank0.get(N, 0) + 1
    n_cls_ok = sum(1 for N in head_cls if len(head_cls[N]) == nnf.get(N))
    incomplete = [N for N in head_cls if len(head_cls[N]) != nnf.get(N)]

    allc, rank0 = {}, {}
    for c in curves.values():
        allc[c["conductor"]] = allc.get(c["conductor"], 0) + 1
        if c["rank"] == 0:
            rank0[c["conductor"]] = rank0.get(c["conductor"], 0) + 1
    assert sum(allc.values()) == len(curves) == 284, "families.json must be the 284 rank-0 curves"
    parsed_match = all(head_rank0.get(N, 0) == n for N, n in rank0.items()) and \
        sum(rank0.values()) == sum(head_rank0.values())

    npass = sum(1 for r in res if is_pass(r))
    nfail = len(res) - npass

    out = []
    w = out.append
    w("# BSD family report — every rank-0 curve of conductor N <= 100\n")
    w("Generated by `scripts/make_report.py` from a `results.json` produced by "
      "`python src/bsd_family.py` (entry point: `./verify.sh`).\n")
    w(f"- Curves checked: **{len(res)}** — PASS {npass}, FAIL {nfail}")
    n_head = sum(head_curves.values())
    w(f"- Completeness witness (raw eclib heads vs count.txt): "
      f"{len(head_cls)} conductors N<=100 with curves, {n_head} curves total; "
      f"isogeny-class counts match NNF for {n_cls_ok}/{len(head_cls)} conductors"
      + (f" (incomplete: {incomplete})" if incomplete else "")
      + f"; rank-0 subset {sum(head_rank0.values())} curves over {len(head_rank0)} "
      f"conductors" + (" — parsed table agrees exactly." if parsed_match else " — MISMATCH vs parsed table!"))
    w(f"- Verified mismatches vs the reference database: **{nfail}**")
    w("")
    w("Reference values are the Cremona eclib `allbsd` columns (T, CP=prod c_p, "
      "OM=real period, L1=L(E,1)/r!, SHA) — the upstream source of the LMFDB "
      "elliptic-curve pages (ecdata@master, live-fetched by `scripts/fetch_cremona.sh`).")
    w("")
    w("Conventions: Omega_E = integral of |omega| over all of E(R) when Delta>0 "
      "(two components), over the identity component when Delta<0 — matching the "
      "OM column; L1 stores L(E,1)/r!. BSD ratio = L(E,1)*T^2/(Omega_E*prod c_p); "
      "predicted Sha = ratio rounded to nearest integer (the rank-0 root number is "
      "+1, so the sign condition holds; see CLAIMS.md).\n")

    w("| label | sgn(D) | Kodaira(c_p) at bad p | T calc/db | mult c_p / prod c_p (db) | Omega_E calc / db | L(E,1) calc / db | ratio | sha pred/db | verdict |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for r in res:
        c = curves[r["label"]]
        kod = " ".join(f"{p}:{v}" for p, v in sorted(r["kodaira"].items(), key=lambda t: int(t[0])))
        mm = r["mismatches"]
        sha_x = " X" if isinstance(mm, list) and any(m.startswith("sha") for m in mm) else ""
        w(f"| {r['label']} | {'+' if r['delta'] > 0 else '-'} | {kod} | "
          f"{r['torsion']}/{c['torsion']}{' X' if int(c['torsion']) != r['torsion'] else ''}{'' if r['torsion_certified'] else '*'} | "
          f"{r.get('tamagawa_mult_part', '?')}/{c['tamagawa_product']}{' X' if int(c['tamagawa_product']) % max(r.get('tamagawa_mult_part', 1), 1) else ''} | "
          f"{r['omega']} / {c['real_period']} | "
          f"{r['l1']} / {c['l1_over']} | "
          f"{r.get('bsd_ratio', '')} | "
          f"{r['sha_predicted']}/{c['sha']}{sha_x} | "
          f"{'PASS' if is_pass(r) else 'FAIL'} |")
    w("")
    w("\\* torsion not certified by the gcd bound alone: exhibited subgroup order "
      "matches the database's proven descent value (CITED); X = mismatch.\n")
    w("Kodaira `?` marks wild additive primes p = 2, 3 where the symbol/f_p/c_p "
      "are CITED from the db (our pure-Python wild port is known-broken there — "
      "see CLAIMS.md); multiplicative fibers at p = 2, 3 are fully re-derived. "
      "The prod c_p column is the cited db CP value; the mult column is the "
      "re-derived multiplicative part, checked to divide it exactly (equality "
      "when no additive primes occur).\n")
    if nfail:
        w("## Flagged mismatches\n")
        for r in res:
            if not is_pass(r):
                w(f"- {r['label']}: {r['mismatches']}")
        w("")
    else:
        w("## Mismatches\n")
        w(f"None: all {len(res)} rank-0 curves agree with every reference quantity "
          "(conductor, a_p<=97, L(E,1)/Omega, period, torsion, Sha) at 1e-12 "
          "relative tolerance, and every cited prod c_p is exactly divisible by "
          "the re-derived multiplicative Tamagawa part.\n")

    w("## Conductor coverage\n")
    w("| N | classes (parsed / NNF) | curves (all) | rank-0 checked |")
    w("|---|---|---|---|")
    for N in sorted(head_cls):
        w(f"| {N} | {len(head_cls[N])} / {nnf.get(N, 0)}"
          f"{' X' if len(head_cls[N]) != nnf.get(N) else ''} | {head_curves[N]} | "
          f"{rank0.get(N, 0)} |")
    w("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(res)} rows, {npass} PASS, {nfail} FAIL")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
